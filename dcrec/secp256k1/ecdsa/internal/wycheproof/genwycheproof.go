// This file is ignored during the regular build. It is called by go generate
// to fetch and generate the compact Wycheproof ECDSA test vectors.
//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"time"
)

const (
	// wycheproofCommit is the Wycheproof git commit for obtaining the test
	// vectors.
	wycheproofCommit = "65ca494727a52944c204441c860b039e6786b99b"

	// vectorsURLPrefix is the URL prefix for obtaining the test vectors.
	vectorsURLPrefix = "https://raw.githubusercontent.com/C2SP/wycheproof/" +
		wycheproofCommit + "/testvectors_v1/"

	outputFile    = "vectors_test.go"
	maxVectorSize = 2 << 20
)

// vectorSource houses details about a Wycheproof JSON test vector file such as
// its URL and expected hash of its contents for a given pinned commit.
type vectorSource struct{ url, hash, name string }

// sourceVectors identifies the test vectors to download along with their
// expected SHA-256 hashes and associated names.
var sourceVectors = []vectorSource{{
	url:  vectorsURLPrefix + "ecdsa_secp256k1_sha256_test.json",
	hash: "43db761c0a2eae71fb0755d355d5130e28ce64a5b07846cf27e7072082597a81",
	name: "ecdsaTestGroups",
}, {
	url:  vectorsURLPrefix + "ecdsa_secp256k1_sha256_bitcoin_test.json",
	hash: "d3729ce83ff9740c45e74921009a4061eff6c09185b8dd1225ccd06ac57048a4",
	name: "ecdsaBitcoinTestGroups",
}}

// vectorTest models a subset of the data in each individual test of the
// Wycheproof JSON vectors.
type vectorTest struct {
	ID     int    `json:"tcId"`
	Result string `json:"result"`
	Msg    string `json:"msg"`
	Sig    string `json:"sig"`
}

// vectorGroup models a subset of the data in each individual test group of the
// Wycheproof JSON vectors.
type vectorGroup struct {
	PublicKey struct {
		Uncompressed string `json:"uncompressed"`
	} `json:"publicKey"`
	Tests []vectorTest `json:"tests"`
}

// vectorFile models a subset of the testGroups field of the Wycheproof JSON
// vectors.
type vectorFile struct {
	TestGroups []vectorGroup `json:"testGroups"`
}

// downloadVectors downloads the file at the provided URL, verifies the SHA-256
// hash of its contents against the provided expected hash, and returns the
// resulting bytes.
//
// The download will fail if the file is larger than [maxVectorSize].
func downloadVectors(client *http.Client, url, expectedHash string) ([]byte, error) {
	response, err := client.Get(url)
	if err != nil {
		return nil, fmt.Errorf("download vectors: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download vectors: unexpected HTTP status %s",
			response.Status)
	}

	data, err := io.ReadAll(io.LimitReader(response.Body, maxVectorSize+1))
	if err != nil {
		return nil, fmt.Errorf("read vectors: %w", err)
	}
	if len(data) > maxVectorSize {
		return nil, fmt.Errorf("downloaded vectors exceed %d bytes",
			maxVectorSize)
	}
	gotHash := fmt.Sprintf("%x", sha256.Sum256(data))
	if gotHash != expectedHash {
		return nil, fmt.Errorf("downloaded vectors SHA-256 mismatch: got %s, "+
			"want %s", gotHash, expectedHash)
	}

	return data, nil
}

func generate() error {
	var output bytes.Buffer
	p := func(format string, args ...interface{}) {
		fmt.Fprintf(&output, format, args...)
	}
	pln := func(format string, args ...interface{}) {
		p(format+"\n", args...)
	}

	pln("// Code generated by genwycheproof.go.  DO NOT EDIT.")
	pln("")
	pln("// These vectors are generated from the following source files from")
	pln("// C2SP/wycheproof commit %s:", wycheproofCommit)
	pln("//")
	for _, src := range sourceVectors {
		pln("// \t%s", filepath.Base(src.url))
	}
	pln("")
	pln("package wycheproof")

	client := &http.Client{Timeout: 30 * time.Second}
	allVectors := make(map[string][]vectorTest)
	for _, src := range sourceVectors {
		// Download and parse the JSON test vectors.
		data, err := downloadVectors(client, src.url, src.hash)
		if err != nil {
			return err
		}
		var vectors vectorFile
		if err := json.Unmarshal(data, &vectors); err != nil {
			return fmt.Errorf("parse vectors: %w", err)
		}
		if len(vectors.TestGroups) == 0 {
			return fmt.Errorf("vectors from %s contain no test groups", src.url)
		}

		// Prune duplicate tests.
		prunedGroups := make([]vectorGroup, 0, len(vectors.TestGroups))
		for _, group := range vectors.TestGroups {
			pubKey := group.PublicKey.Uncompressed
			if pubKey == "" {
				return fmt.Errorf("test group has no uncompressed public key")
			}

			pubKeyTests := allVectors[pubKey]
			isDuplicateTest := func(test vectorTest) bool {
				for _, existing := range pubKeyTests {
					if test.Msg == existing.Msg && test.Sig == existing.Sig &&
						test.Result == existing.Result {

						return true
					}
				}
				return false
			}

			prunedTests := make([]vectorTest, 0, len(group.Tests))
			for _, test := range group.Tests {
				switch test.Result {
				case "valid", "invalid":
				default:
					return fmt.Errorf("test case %d has unknown result %q",
						test.ID, test.Result)
				}
				if isDuplicateTest(test) {
					continue
				}
				pubKeyTests = append(pubKeyTests, test)

				prunedTests = append(prunedTests, test)
			}
			if len(prunedTests) > 0 {
				prunedGroup := group
				prunedGroup.Tests = prunedTests
				prunedGroups = append(prunedGroups, prunedGroup)
			}

			allVectors[pubKey] = pubKeyTests
		}
		if len(prunedGroups) == 0 {
			continue
		}

		// Write pruned test cases.
		pln("")
		pln("var %s = []ecdsaTestGroup{", src.name)
		for _, group := range prunedGroups {
			pln("\t{%q, []ecdsaTest{", group.PublicKey.Uncompressed)
			for i, test := range group.Tests {
				p("\t\t{%d, %q, %q, %v}", test.ID, test.Msg, test.Sig,
					test.Result == "valid")
				if i == len(group.Tests)-1 {
					p("}}")
				}
				pln(",")
			}
		}
		pln("}")
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		return fmt.Errorf("write generated source: %w", err)
	}
	return nil
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
