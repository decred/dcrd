// This file is ignored during the regular build. It is called by go generate
// to fetch and generate the compact Wycheproof ECDSA test vectors.
//go:build ignore

package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"time"
)

const (
	vectorURL = "https://raw.githubusercontent.com/C2SP/wycheproof/" +
		"65ca494727a52944c204441c860b039e6786b99b/" +
		"testvectors_v1/ecdsa_secp256k1_sha256_test.json"
	vectorSHA256 = "43db761c0a2eae71fb0755d355d5130e28ce64a5b07846cf27e7072082597a81"

	bitcoinVectorURL = "https://raw.githubusercontent.com/C2SP/wycheproof/" +
		"65ca494727a52944c204441c860b039e6786b99b/" +
		"testvectors_v1/ecdsa_secp256k1_sha256_bitcoin_test.json"
	bitcoinVectorSHA256 = "d3729ce83ff9740c45e74921009a4061eff6c09185b8dd1225ccd06ac57048a4"

	outputFile    = "wycheproof_vectors_test.go"
	maxVectorSize = 2 << 20
)

type vectorFile struct {
	TestGroups []vectorGroup `json:"testGroups"`
}

type vectorGroup struct {
	PublicKey struct {
		Uncompressed string `json:"uncompressed"`
	} `json:"publicKey"`
	Tests []vectorTest `json:"tests"`
}

type vectorTest struct {
	ID     int    `json:"tcId"`
	Result string `json:"result"`
	Msg    string `json:"msg"`
	Sig    string `json:"sig"`
}

type vectorSource struct{ url, hash, tableName string }

func main() {
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

func generate() error {
	client := &http.Client{Timeout: 30 * time.Second}
	sources := []vectorSource{
		{vectorURL, vectorSHA256, "wycheproofECDSATestGroups"},
		{bitcoinVectorURL, bitcoinVectorSHA256, "wycheproofECDSABitcoinTestGroups"},
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by genwycheproof.go; DO NOT EDIT.\n" +
		"// The source files are from C2SP/wycheproof commit\n" +
		"// 65ca494727a52944c204441c860b039e6786b99b and are\n" +
		"// ecdsa_secp256k1_sha256_test.json and\n" +
		"// ecdsa_secp256k1_sha256_bitcoin_test.json.\n\npackage ecdsa\n\n")

	for _, vectorSource := range sources {
		vectors, err := downloadVectors(client, vectorSource.url, vectorSource.hash)
		if err != nil {
			return err
		}
		if len(vectors.TestGroups) == 0 {
			return fmt.Errorf("vectors from %s contain no test groups",
				vectorSource.url)
		}
		if err := writeTestGroups(&source, vectorSource.tableName,
			vectors.TestGroups); err != nil {
			return err
		}
	}

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		return fmt.Errorf("write generated source: %w", err)
	}
	return nil
}

func downloadVectors(client *http.Client, url, expectedHash string) (*vectorFile, error) {
	response, err := client.Get(url)
	if err != nil {
		return nil, fmt.Errorf("download vectors: %w", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download vectors: unexpected HTTP status %s",
			response.Status)
	}

	data, err := io.ReadAll(io.LimitReader(response.Body, maxVectorSize+1))
	if err != nil {
		return nil, fmt.Errorf("read vectors: %w", err)
	}
	if len(data) > maxVectorSize {
		return nil, fmt.Errorf("downloaded vectors exceed %d bytes", maxVectorSize)
	}
	gotHash := fmt.Sprintf("%x", sha256.Sum256(data))
	if gotHash != expectedHash {
		return nil, fmt.Errorf("downloaded vectors SHA-256 mismatch: got %s, want %s",
			gotHash, expectedHash)
	}

	var vectors vectorFile
	if err := json.Unmarshal(data, &vectors); err != nil {
		return nil, fmt.Errorf("parse vectors: %w", err)
	}
	return &vectors, nil
}

func writeTestGroups(source *bytes.Buffer, tableName string, groups []vectorGroup) error {
	fmt.Fprintf(source, "var %s = []wycheproofECDSATestGroup{\n", tableName)
	for _, group := range groups {
		if group.PublicKey.Uncompressed == "" {
			return fmt.Errorf("test group has no uncompressed public key")
		}
		tests := group.Tests
		if tableName == "wycheproofECDSATestGroups" {
			// The selected standard tcIds are 464-476. Earlier vectors are omitted
			// because the Bitcoin file covers them; tcId 476 still exercises a valid
			// high-S signature with plain Verify; pinned hashes stabilize the list.
			tests = make([]vectorTest, 0, 13)
			for _, test := range group.Tests {
				switch test.ID {
				case 464, 465, 466, 467, 468, 469, 470, 471, 472, 473, 474, 475, 476:
					tests = append(tests, test)
				}
			}
		}
		if len(tests) == 0 {
			continue
		}
		fmt.Fprintf(source, "\t{%q, []wycheproofECDSATest{\n", group.PublicKey.Uncompressed)
		for i, test := range tests {
			switch test.Result {
			case "valid", "invalid", "acceptable":
			default:
				return fmt.Errorf("test case %d has unknown result %q", test.ID,
					test.Result)
			}

			writeTestCase(source, test, i == len(tests)-1)
		}
	}
	fmt.Fprintln(source, "}")
	return nil
}

func writeTestCase(source *bytes.Buffer, test vectorTest, lastInGroup bool) {
	fmt.Fprintf(source, "\t\t{%d, %q, %q, %q}", test.ID, test.Msg,
		test.Sig, test.Result)
	if lastInGroup {
		fmt.Fprint(source, "}}")
	}
	fmt.Fprintln(source, ",")
}
